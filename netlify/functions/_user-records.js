export function inferRole(email, explicitRole) {
  if (explicitRole === 'admin' || explicitRole === 'Contractor' || explicitRole === 'Homeowner') {
    return explicitRole;
  }
  const normalized = String(email || '').trim().toLowerCase();
  if (normalized === 'blaztprod@gmail.com') return 'admin';
  if (normalized.includes('contractor') || normalized.includes('contrator') || normalized.includes('builder') || normalized.includes('trades')) {
    return 'Contractor';
  }
  return 'Homeowner';
}

export function inferName(email, explicitName) {
  if (explicitName && explicitName.trim()) return explicitName.trim();
  const localPart = String(email || 'user').split('@')[0] || 'user';
  return localPart.replace(/[._-]+/g, ' ').replace(/\b\w/g, (char) => char.toUpperCase());
}

export function getTrialFields(role, createdAt) {
  if (role !== 'Contractor') {
    return { accountPlan: 'standard', trialStartedAt: undefined, trialEndsAt: undefined, subscriptionLevel: 'none' };
  }
  const started = createdAt || new Date().toISOString();
  const ends = new Date(started);
  ends.setDate(ends.getDate() + 14);
  return {
    accountPlan: 'trial',
    trialStartedAt: started,
    trialEndsAt: ends.toISOString(),
    subscriptionLevel: ends.getTime() > Date.now() ? 'trial' : 'none',
  };
}

export function buildUserAccountPayload({
  uid,
  email,
  role,
  createdAt,
  updatedAt,
  isDisabled = false,
  isVerified,
  licenseStatus,
  subscriptionLevel,
  accountPlan,
  trialStartedAt,
  trialEndsAt,
}) {
  const finalRole = inferRole(email, role);
  const trialFields = getTrialFields(finalRole, createdAt);
  return Object.fromEntries(
    Object.entries({
      uid,
      email,
      role: finalRole,
      isVerified: typeof isVerified === 'boolean' ? isVerified : finalRole === 'admin',
      isDisabled,
      licenseStatus: licenseStatus ?? (finalRole === 'Contractor' ? 'Pending' : undefined),
      accountPlan: accountPlan ?? trialFields.accountPlan,
      trialStartedAt: trialStartedAt ?? trialFields.trialStartedAt,
      trialEndsAt: trialEndsAt ?? trialFields.trialEndsAt,
      subscriptionLevel: subscriptionLevel ?? trialFields.subscriptionLevel,
      createdAt,
      updatedAt,
    }).filter(([, value]) => value !== undefined)
  );
}

