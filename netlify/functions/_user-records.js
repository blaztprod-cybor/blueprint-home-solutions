export async function getVerifiedRequestUser({ authorizationHeader, adminAuth, adminDb }) {
  const token = String(authorizationHeader || '').replace(/^Bearer\s+/i, '').trim();
  if (!token) {
    throw new Error('Missing authorization token.');
  }

  const decoded = await adminAuth.verifyIdToken(token);
  const email = String(decoded.email || '').toLowerCase();
  const roleFromClaim = decoded.role;
  const userDoc = await adminDb.collection(USERS_COLLECTION).doc(decoded.uid).get().catch(() => null);
  const roleFromDoc = userDoc?.exists ? userDoc.data()?.role : undefined;

  return {
    uid: decoded.uid,
    email,
    claims: decoded,
    isAdmin: roleFromClaim === 'admin' || roleFromDoc === 'admin' || email === 'blaztprod@gmail.com',
  };
}
